COURS COMPLET JURISIA — DROIT DES OBLIGATIONS

Présentation

Le droit des obligations organise les rapports juridiques dans lesquels une
personne, le créancier, peut exiger d'une autre personne, le débiteur, une
prestation, une abstention ou une réparation. Il constitue une matière
transversale : contrat de vente, bail, travail, financement, responsabilité,
transaction et nombreux services reposent sur une obligation.

Ce cours propose un parcours complet de formation. Il distingue les règles
communes, les mécanismes contractuels, la responsabilité civile, les
quasi-contrats, le régime général et les contrats spéciaux. Les références
doctrinales transmises par l'équipe servent de bibliographie de travail. Les
règles doivent être confrontées au texte officiel, à la jurisprudence et au
droit applicable au pays concerné, notamment lorsque le dossier relève du
droit burkinabè ou de l'espace OHADA.

Objectifs de formation

À la fin du cours, l'étudiant doit pouvoir :

1. qualifier une obligation et identifier sa source ;
2. vérifier la formation, la validité et les effets d'un contrat ;
3. analyser une inexécution et proposer les remèdes adaptés ;
4. construire un raisonnement de responsabilité civile ;
5. distinguer les principaux quasi-contrats et contrats spéciaux ;
6. rédiger une clause claire et traiter un cas pratique avec méthode.

PARTIE I — LES FONDAMENTAUX DE L'OBLIGATION

Chapitre 1 — La notion d'obligation

L'obligation est un lien de droit entre deux patrimoines ou, plus largement,
entre deux sujets de droit identifiables. Le créancier dispose d'une prétention
et le débiteur est tenu d'une prestation. La prestation peut consister à donner
une chose, à accomplir un fait ou à s'abstenir d'agir. Une dette de paiement,
la remise d'un bien, la réalisation d'un ouvrage, la confidentialité et la
non-concurrence sont autant de manifestations possibles.

L'obligation se distingue du simple devoir moral par sa sanction juridique.
Elle se distingue aussi du droit réel : le droit réel porte directement sur une
chose et est opposable selon son régime propre, tandis que le droit de
créance permet d'exiger une prestation d'une personne déterminée. Dans la
pratique, un même projet combine souvent les deux : une vente crée des
obligations entre vendeur et acheteur et organise ensuite le transfert d'un
droit sur le bien.

Il faut enfin distinguer l'obligation civile, qui peut être judiciairement
exécutée, de l'obligation naturelle, qui repose sur un devoir reconnu par la
conscience juridique mais dont l'exécution volontaire ne doit pas être
confondue avec une contrainte judiciaire. Toute qualification dépend du droit
applicable et des faits établis.

Chapitre 2 — Les sources et les classifications

Les principales sources sont le contrat, le fait juridique, la loi et, selon
les systèmes, certains actes unilatéraux. Le contrat naît d'un accord destiné
à produire des effets de droit. Le fait juridique produit des effets sans que
ces effets aient nécessairement été recherchés : dommage, gestion spontanée
d'une affaire d'autrui ou paiement indu. La loi peut imposer une obligation
alimentaire, fiscale, de sécurité ou de restitution.

On distingue les obligations de donner, de faire et de ne pas faire ; les
obligations de moyens, dans lesquelles le débiteur doit déployer des diligences
raisonnables, et de résultat, dans lesquelles un résultat déterminé est promis
sous réserve des causes d'exonération ; les obligations pécuniaires et les
obligations en nature ; enfin les obligations instantanées, successives ou
continues.

La qualification n'est pas décorative. Elle détermine la preuve attendue, la
mesure de l'exécution, la portée d'une clause et les conséquences d'un
incident. Pour qualifier, il faut partir du texte, de l'économie de l'accord,
du comportement des parties et de la finalité concrète de la prestation.

PARTIE II — LE CONTRAT

Chapitre 3 — La liberté contractuelle et la bonne foi

La liberté contractuelle permet, dans les limites de la loi et de l'ordre
public, de contracter ou non, de choisir son cocontractant et de déterminer le
contenu de l'accord. Elle n'autorise pas à écarter une règle impérative, à
organiser une fraude ou à imposer une clause portant atteinte aux droits
protégés.

Le contrat doit être négocié, formé et exécuté de bonne foi. La bonne foi
impose loyauté, cohérence et coopération minimale. Elle peut commander de
révéler une information déterminante, de ne pas provoquer artificiellement une
défaillance ou de permettre les vérifications nécessaires à l'exécution. Elle
ne permet pas au juge de réécrire librement le contrat : son rôle consiste à
faire respecter le cadre juridique et la volonté valablement exprimée.

Chapitre 4 — La formation du contrat

La formation suppose une offre suffisamment précise et une acceptation qui lui
correspond. L'offre doit manifester une volonté de s'engager et contenir les
éléments essentiels de l'opération. Une invitation à négocier ou une publicité
générale peut ne constituer qu'une sollicitation. L'acceptation doit être
extérieure, non équivoque et intervenir dans les conditions prévues ; une
acceptation modifiée est en principe une nouvelle proposition.

Les pourparlers restent libres, mais leur rupture peut engager la responsabilité
de celui qui agit brutalement, déloyalement ou après avoir créé une confiance
légitime. Les dépenses raisonnables et certaines informations confidentielles
méritent une protection spécifique. Un accord de confidentialité peut être
conclu avant même le contrat principal.

Le contrat électronique obéit aux mêmes exigences substantielles. Il faut
pouvoir identifier le professionnel ou le cocontractant, conserver la version
acceptée, dater l'acceptation et sécuriser la preuve. Les cases précochées,
les conditions cachées et les parcours ambigus fragilisent le consentement.

Chapitre 5 — Validité : consentement, capacité et contenu

Le consentement doit être libre et éclairé. L'erreur ne justifie une remise en
cause que lorsqu'elle porte sur un élément déterminant et qu'elle est
juridiquement pertinente. Le dol résulte de manœuvres, de mensonges ou d'une
rétention intentionnelle d'information déterminante. La violence vicie le
consentement lorsqu'une pression illégitime fait craindre un mal sérieux.

La capacité s'apprécie au regard du statut de la personne, de son âge, de sa
protection et des pouvoirs du représentant. Une société doit agir par un
organe ou un mandataire habilité. Avant la signature, il faut donc vérifier
l'identité, les pouvoirs, les autorisations internes et, lorsque nécessaire,
les règles de représentation.

Le contenu doit être licite, possible et suffisamment déterminé ou
déterminable. La prestation, le prix ou la méthode de calcul, la durée, les
modalités de livraison et les obligations essentielles doivent être
compréhensibles. Une clause obscure se prête à l'interprétation ; une clause
contradictoire ou manifestement déséquilibrée peut être écartée selon le
régime applicable. Les clauses limitatives de responsabilité ne peuvent pas
anéantir l'obligation essentielle et doivent respecter les règles protectrices
applicables au contrat.

Chapitre 6 — Preuve et interprétation

La preuve d'un contrat dépend de la nature de l'opération, de sa valeur, du
statut des parties et des règles spéciales. Il faut conserver l'offre, les
versions négociées, les annexes, les factures, les procès-verbaux de réception,
les échanges et les éléments de signature. Un écrit signé ne suffit pas si les
annexes auxquelles il renvoie sont absentes.

L'interprétation recherche la commune intention lorsque le texte ne suffit pas.
Elle tient compte des clauses entre elles, de la pratique antérieure, des
usages et de la finalité économique. Les ambiguïtés d'un document standard
peuvent être interprétées contre celui qui l'a rédigé lorsque le droit
applicable le prévoit. La priorité reste la cohérence : une définition doit
être utilisée de manière constante et chaque obligation doit avoir un
responsable, un délai et un mode de preuve.

PARTIE III — EFFETS ET INEXÉCUTION

Chapitre 7 — Effets du contrat

Le contrat valablement formé oblige les parties. Il fixe une règle de conduite
et ne peut être modifié ou résilié unilatéralement que si la loi, le contrat ou
une situation reconnue l'autorise. Les parties doivent accomplir les
prestations promises, coopérer à leur réalisation et respecter les obligations
accessoires de sécurité, information, confidentialité ou restitution.

Le contrat produit en principe ses effets entre les parties. La stipulation
pour autrui permet toutefois de conférer un droit à un tiers. La cession de
contrat, la cession de créance et la sous-traitance exigent de distinguer le
transfert de la relation, le transfert du droit au paiement et l'exécution par
un tiers. Les formalités et consentements requis doivent être vérifiés avant
toute opération.

Chapitre 8 — L'inexécution et ses remèdes

Une inexécution peut être totale, partielle, tardive ou défectueuse. Le
créancier doit établir l'obligation, l'échéance, le manquement et le préjudice
éventuel. Le débiteur peut opposer une force majeure, le fait du créancier,
une impossibilité légitime ou une autre cause prévue par le droit applicable.

La mise en demeure rappelle l'obligation, le manquement, le délai accordé et
la conséquence envisagée. Elle doit être adressée par un moyen permettant de
prouver la réception. Selon le dossier, les remèdes peuvent comprendre :

- l'exécution forcée en nature lorsque la prestation reste possible et
  proportionnée ;
- l'exécution par remplacement ou la réparation du défaut ;
- la réduction du prix lorsque la prestation conserve une utilité partielle ;
- la résolution ou la résiliation du contrat ;
- la suspension de sa propre obligation dans un contrat synallagmatique ;
- les dommages-intérêts correspondant au dommage prouvé et imputable.

Ces remèdes ne se cumulent pas mécaniquement. Il faut vérifier leur
compatibilité, respecter la procédure contractuelle et limiter le dommage. Une
clause pénale peut fixer forfaitairement la sanction, mais son montant et son
contrôle dépendent du régime applicable.

Chapitre 9 — Responsabilité contractuelle et réparation

La responsabilité contractuelle suppose un contrat valable, une inexécution,
un dommage et un lien de causalité. Le dommage doit être certain ou
suffisamment établi ; il peut être matériel, financier ou, lorsque le droit le
reconnaît, moral. La réparation cherche à replacer la victime dans la
situation où elle se serait trouvée sans le manquement, sans enrichissement
injustifié.

La prévisibilité, la causalité et l'obligation de limiter raisonnablement son
propre dommage encadrent l'indemnisation. Une perte de chance doit être
identifiée comme la disparition actuelle d'une probabilité sérieuse, et non
comme un gain certain. Le professionnel doit documenter les coûts, les pertes,
les délais et les mesures prises pour éviter l'aggravation.

PARTIE IV — RESPONSABILITÉ CIVILE EXTRACONTRACTUELLE

Chapitre 10 — Le raisonnement en trois éléments

La responsabilité extracontractuelle se raisonne autour d'un fait générateur,
d'un dommage et d'un lien de causalité. Le fait peut être une faute, un fait
des choses, un fait d'autrui ou un régime spécial. La faute s'apprécie selon
le comportement qu'une personne prudente aurait adopté dans les mêmes
circonstances, sans oublier les règles professionnelles et de sécurité.

Le dommage doit être personnel, certain et licite selon les catégories
reconnues. Il peut être corporel, matériel ou moral. En présence d'une
victime indirecte, il faut démontrer son préjudice propre. Le lien causal
demande de relier le fait au dommage sans ignorer les causes concurrentes,
le fait de la victime ou l'intervention d'un tiers.

Chapitre 11 — Exonérations et régimes particuliers

La force majeure, le fait d'un tiers et la faute de la victime peuvent réduire
ou exclure la responsabilité si leurs conditions sont réunies. L'acceptation
des risques ne vaut pas renonciation générale à toute réparation. Les clauses
de non-responsabilité sont encadrées et ne peuvent neutraliser les règles
impératives, la faute lourde ou le dommage corporel lorsque le droit les
protège.

Les produits défectueux, les accidents de circulation, les dommages causés
par les bâtiments, les relations de travail et les activités professionnelles
peuvent relever de régimes spéciaux. La méthode reste la même : identifier le
texte spécial, vérifier ses conditions, puis seulement appliquer les règles
générales complémentaires.

PARTIE V — QUASI-CONTRATS ET RÉGIME GÉNÉRAL

Chapitre 12 — Les quasi-contrats

La gestion d'affaires naît lorsqu'une personne intervient utilement dans les
affaires d'autrui sans mandat préalable. Le gérant doit agir avec prudence,
informer lorsque c'est possible et rendre compte ; le maître de l'affaire doit
prendre en charge les dépenses utiles selon les conditions prévues par le
droit.

Le paiement de l'indu permet de demander restitution lorsqu'une personne a
payé ce qu'elle ne devait pas ou à la mauvaise personne. Il faut identifier le
paiement, l'absence de dette ou l'erreur, le bénéficiaire et les règles de
restitution. L'enrichissement injustifié intervient de manière subsidiaire
lorsqu'un enrichissement, un appauvrissement corrélatif et l'absence de
justification juridique sont établis.

Chapitre 13 — Paiement et extinction

Le paiement est l'exécution de la prestation due. Il faut vérifier l'identité
du payeur, la qualité du destinataire, la date, le montant, l'imputation et la
preuve. Lorsque plusieurs dettes existent, l'imputation peut dépendre du choix
du débiteur, de l'accord des parties ou des règles supplétives.

D'autres mécanismes éteignent ou transforment l'obligation : compensation de
dettes réciproques, remise de dette, novation, confusion, prescription,
transaction et, selon les systèmes, impossibilité définitive. La transaction
doit identifier le différend et les concessions réciproques ; elle ne doit pas
être utilisée pour renoncer à des droits indisponibles.

Chapitre 14 — Pluralité de débiteurs et de créanciers

Une obligation conjointe se divise en parts, tandis que la solidarité permet au
créancier de réclamer l'intégralité à l'un des débiteurs lorsque la loi ou le
contrat la prévoit. Celui qui paie plus que sa part peut exercer un recours
contre les autres. La solidarité ne se présume pas toujours : il faut vérifier
le texte applicable et la rédaction exacte.

La cession de créance transfère le droit au paiement sous réserve des
conditions de forme et d'opposabilité. La délégation et la cession de dette
peuvent modifier les personnes tenues. Chaque opération doit préciser les
garanties, les exceptions opposables, la date d'effet et l'information du
débiteur ou du créancier concerné.

PARTIE VI — CONTRATS SPÉCIAUX

Chapitre 15 — Vente et échange

La vente organise le transfert d'un bien ou d'un droit contre un prix. Les
points essentiels sont la chose, le prix, l'identification des parties, le
transfert, la délivrance, les risques, les garanties et les conditions de
paiement. La conformité du bien, les vices cachés, la réserve de propriété et
la clause de rétractation doivent être traités selon le droit applicable.

L'échange suit une logique comparable, mais chaque partie fournit un bien ou
un droit en contrepartie d'un autre. Les contrats de fourniture et de
distribution ajoutent des obligations de quantité, qualité, exclusivité,
territoire, conformité et préavis.

Chapitre 16 — Bail et mise à disposition

Le bail confère la jouissance temporaire d'un bien contre un loyer ou une
contrepartie. Il doit préciser la désignation des lieux, la durée, le montant,
les charges, l'état des lieux, les réparations, l'assurance, la sous-location,
la cession et la fin du contrat. Le bail à usage d'habitation et le bail à
usage professionnel peuvent obéir à des règles différentes et doivent être
qualifiés avant la rédaction.

Le bailleur doit délivrer un bien conforme à l'usage convenu et assurer la
jouissance paisible. Le locataire doit payer, user raisonnablement des lieux,
respecter la destination et restituer le bien. Les impayés, dégradations et
troubles doivent être traités par une procédure documentée.

Chapitre 17 — Entreprise, prestation et mandat

Dans une prestation de service, le contrat doit décrire le livrable, les
critères d'acceptation, les délais, les dépendances, la propriété des travaux,
la confidentialité, la maintenance et la responsabilité. Une obligation de
moyens doit être distinguée d'un résultat promis.

Le mandat confie à une personne le pouvoir d'agir pour le compte d'une autre.
Le mandataire doit respecter les instructions, rendre compte et éviter les
conflits d'intérêts. Le mandant doit fournir les moyens, rembourser les frais
justifiés et respecter les actes accomplis dans les limites du pouvoir.

Chapitre 18 — Prêt, dépôt, partenariat et transaction

Le prêt porte sur une chose ou une somme et doit préciser la remise, la durée,
la restitution, la rémunération éventuelle et les garanties. Le dépôt organise
la garde et la restitution d'un bien. Le partenariat doit déterminer les
apports, les rôles, la propriété des résultats, le partage des revenus, les
pertes, la sortie et le règlement des différends.

La transaction met fin à un différend par des concessions réciproques. Elle
doit être rédigée avec précision : périmètre du litige, obligations de chaque
partie, délais, confidentialité, quittance éventuelle et conséquences du
manquement.

PARTIE VII — TECHNIQUE CONTRACTUELLE

Chapitre 19 — Construire un contrat sûr

Une rédaction professionnelle suit une séquence : identifier les parties et
leurs pouvoirs ; définir les termes ; décrire l'objet et les livrables ; fixer
les délais et jalons ; déterminer le prix et les taxes ; répartir les risques ;
prévoir la preuve, l'audit, la confidentialité, les données, la propriété
intellectuelle, la sous-traitance, la force majeure, la résiliation et le
règlement des différends.

Chaque clause doit répondre à quatre questions : qui agit, que doit-il faire,
quand et comment prouver l'exécution ? Les annexes doivent être numérotées,
datées et intégrées par une clause de hiérarchie documentaire. Les définitions
doivent rester stables et les obligations essentielles doivent être lisibles.

Une clause de délai doit préciser le point de départ, le calendrier, les
événements suspensifs, la notification et la sanction. Une clause de prix doit
indiquer le montant ou la formule, l'unité, la devise, les taxes, la facturation
et la date d'exigibilité. Une clause de sortie doit distinguer résiliation pour
convenance, résiliation pour manquement, liquidation des prestations en cours
et restitution des données.

Chapitre 20 — Méthode de cas pratique

La méthode JurisIA suit cinq étapes. Premièrement, sélectionner les faits
juridiquement utiles et établir une chronologie. Deuxièmement, qualifier la
relation : vente, bail, mandat, prestation, responsabilité ou autre.
Troisièmement, formuler la question de droit. Quatrièmement, exposer la règle
applicable et ses conditions. Cinquièmement, appliquer chaque condition aux
faits, discuter les arguments adverses et conclure avec une action concrète.

Une bonne consultation sépare les faits certains, les faits à prouver et les
hypothèses. Elle propose les pièces à réunir : contrat et annexes, preuves de
livraison, factures, mises en demeure, échanges, constats, rapports, attestations
et justificatifs du préjudice. Elle indique aussi les délais et les risques
sans présenter une probabilité comme une certitude.

FICHES OPÉRATIONNELLES

Checklist avant signature : identité et pouvoirs vérifiés ; objet déterminé ;
prix et taxes lisibles ; durée et renouvellement précisés ; obligations
essentielles identifiées ; délais et réception organisés ; garanties et
responsabilité équilibrées ; confidentialité et données couvertes ; propriété
des livrables réglée ; résiliation et règlement des différends prévus ; annexes
signées et version finale archivée.

Checklist en cas d'inexécution : conserver les preuves ; qualifier le
manquement ; vérifier le délai et la clause applicable ; mettre en demeure ;
mesurer le dommage ; prendre des mesures conservatoires ; choisir un remède
proportionné ; vérifier la prescription ; négocier sans renoncer implicitement
à ses droits ; préparer, si nécessaire, la procédure compétente.

Checklist de rédaction : utiliser des phrases courtes ; une obligation par
paragraphe ; des verbes d'action ; des dates et seuils mesurables ; une
définition unique par terme ; aucune contradiction entre le corps et les
annexes ; une clause de priorité documentaire ; un mécanisme de notification ;
un responsable désigné pour chaque livrable.

Conclusion

Le droit des obligations devient maîtrisable lorsque l'on relie qualification,
preuve, exécution et remède. Le contrat ne doit pas seulement exprimer une
intention : il doit rendre l'exécution observable, répartir les risques et
prévoir une réponse au désaccord. La responsabilité et les quasi-contrats
complètent cette logique en traitant les situations qui naissent en dehors de
l'accord.

