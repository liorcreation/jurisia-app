COURS COMPLET JURISIA — DROIT DES OBLIGATIONS

PRÉSENTATION ET OBJECTIFS

Le droit des obligations organise les rapports dans lesquels une personne, le
créancier, peut exiger d'une autre personne, le débiteur, une prestation, une
abstention ou une réparation. Il se retrouve dans la vente, le bail, le
travail, le financement, les services, la responsabilité et la transaction.

Ce cours suit un parcours complet : notions fondamentales, contrat,
inexécution, responsabilité civile, quasi-contrats, régime général, contrats
spéciaux et technique contractuelle. Les ressources transmises par l'équipe
ont servi à orienter les thèmes et la progression. Le texte est une création
pédagogique originale JurisIA. Il faut confronter chaque dossier au droit
positif, aux textes officiels et aux règles territoriales applicables,
notamment en droit burkinabè et dans l'espace OHADA.

PARTIE I — LES FONDAMENTAUX DE L'OBLIGATION

1. Notion et utilité

L'obligation est un lien de droit entre un créancier et un débiteur. Elle peut
porter sur le paiement d'une somme, la remise d'une chose, l'accomplissement
d'un service ou une abstention. Elle se distingue du devoir moral par sa
sanction juridique et du droit réel parce qu'elle donne d'abord une prétention
contre une personne déterminée.

Les obligations sont classées selon leur objet : donner, faire ou ne pas faire;
selon leur intensité : moyens ou résultat; selon leur durée : instantanées,
successives ou continues; et selon leur nature : pécuniaires ou en nature. La
qualification guide la preuve, le contrôle de l'exécution et le choix du
remède en cas de manquement.

2. Sources

Les sources principales sont le contrat, le fait juridique, la loi et certains
actes unilatéraux. Le contrat repose sur un accord destiné à produire des
effets de droit. Le fait juridique produit un effet juridique sans que cet
effet ait nécessairement été recherché : dommage, gestion spontanée d'une
affaire, paiement indu ou enrichissement injustifié. La loi peut imposer une
obligation de sécurité, de restitution, d'entretien ou de réparation.

PARTIE II — LE CONTRAT

3. Liberté contractuelle et bonne foi

La liberté contractuelle permet de contracter ou non, de choisir son partenaire
et de déterminer le contenu de l'accord, dans les limites de la loi et de
l'ordre public. La bonne foi commande loyauté, cohérence, coopération et
absence de manœuvre destinée à provoquer artificiellement la défaillance de
l'autre partie.

4. Offre, acceptation et pourparlers

Une offre doit manifester une volonté de s'engager et contenir les éléments
essentiels de l'opération. L'acceptation doit être extérieure, non équivoque et
conforme à l'offre. Une réponse qui modifie un élément essentiel constitue en
principe une nouvelle proposition. Les pourparlers sont libres, mais une
rupture brutale ou déloyale peut engager la responsabilité de son auteur.

L'accord électronique doit permettre d'identifier les parties, de conserver la
version acceptée, de dater l'acceptation et de sécuriser la preuve. Les
conditions générales doivent être accessibles avant l'acceptation et les
annexes effectivement disponibles.

5. Validité du contrat

Le consentement doit être libre et éclairé. L'erreur n'est pertinente que si
elle porte sur un élément déterminant. Le dol suppose une manœuvre, un mensonge
ou une dissimulation intentionnelle ayant provoqué l'engagement. La violence
vicie le consentement lorsqu'une pression illégitime fait craindre un mal
sérieux.

La capacité s'apprécie selon l'âge, la protection, le statut de la personne et
les pouvoirs du représentant. Une société doit agir par un organe ou un
mandataire habilité. Le contenu doit être licite, possible et déterminé ou
déterminable. L'objet, le prix ou son mode de calcul, la durée, les délais et
les prestations essentielles doivent être lisibles.

6. Preuve et interprétation

Il faut conserver l'offre, les versions négociées, les annexes, les factures,
les preuves de livraison, les procès-verbaux de réception, les notifications
et les éléments de signature. L'interprétation recherche la cohérence du
document, la commune intention, la pratique des parties, les usages et la
finalité de l'opération. Une définition doit rester constante et chaque
obligation doit avoir un responsable, une échéance et un mode de preuve.

7. Effets du contrat

Le contrat valablement formé oblige les parties. Elles doivent exécuter les
prestations promises et les obligations accessoires de coopération,
d'information, de sécurité, de confidentialité et de restitution. Le contrat
produit en principe ses effets entre les parties; la stipulation pour autrui,
la cession de créance, la cession de contrat et la sous-traitance obéissent à
des conditions propres qu'il faut vérifier avant l'opération.

PARTIE III — INEXÉCUTION ET RESPONSABILITÉ CONTRACTUELLE

8. Identifier l'inexécution

L'inexécution peut être totale, partielle, tardive ou défectueuse. Le créancier
doit établir l'obligation, l'échéance, le manquement et, s'il demande une
indemnisation, le dommage et le lien de causalité. Le débiteur peut invoquer
une cause d'exonération, le fait du créancier, une impossibilité ou une cause
prévue par le contrat.

La mise en demeure rappelle l'obligation, décrit le manquement, fixe un délai
raisonnable et indique la suite envisagée. Elle est envoyée par un moyen qui
permet de prouver sa réception. Le créancier doit aussi éviter d'aggraver son
propre dommage.

9. Les remèdes

Selon la situation, le créancier peut demander l'exécution en nature si elle
reste possible et proportionnée, une exécution par remplacement, une réduction
du prix, la suspension de sa propre prestation, la résolution ou résiliation,
et des dommages-intérêts. Ces remèdes doivent être compatibles, respecter la
procédure contractuelle et tenir compte de la gravité du manquement.

La responsabilité contractuelle suppose un contrat valable, une inexécution,
un dommage et un lien causal. Le dommage doit être certain ou suffisamment
établi. Il peut être matériel, financier ou moral lorsque le droit applicable
le reconnaît. La perte de chance correspond à la disparition d'une probabilité
sérieuse et ne doit pas être confondue avec un gain certain.

PARTIE IV — RESPONSABILITÉ CIVILE EXTRACONTRACTUELLE

10. Le raisonnement en trois éléments

La responsabilité extracontractuelle se construit autour d'un fait générateur,
d'un dommage et d'un lien de causalité. Le fait peut être une faute, le fait
d'une chose, le fait d'autrui ou un régime spécial. La faute s'apprécie par
rapport au comportement raisonnable attendu dans les mêmes circonstances.

Le dommage doit être personnel, certain et juridiquement réparable. Il peut
être corporel, matériel ou moral. Le lien de causalité relie le fait au
dommage et oblige à examiner les causes concurrentes, le fait de la victime et
l'intervention d'un tiers.

11. Exonérations et régimes spéciaux

La force majeure, le fait d'un tiers et la faute de la victime peuvent réduire
ou exclure la responsabilité lorsque leurs conditions sont réunies. Les
produits défectueux, les accidents de circulation, les dommages causés par un
bâtiment, les relations de travail et certaines activités professionnelles
peuvent relever de textes spéciaux. Il faut identifier ce texte avant
d'appliquer les règles générales.

PARTIE V — QUASI-CONTRATS ET RÉGIME GÉNÉRAL

12. Gestion d'affaires, paiement indu et enrichissement injustifié

La gestion d'affaires concerne l'intervention utile d'une personne dans les
affaires d'autrui sans mandat préalable. Le gérant agit avec prudence, informe
lorsque cela est possible et rend compte. Le maître de l'affaire prend en
charge les dépenses utiles selon les conditions prévues.

Le paiement de l'indu permet la restitution d'une somme ou d'une prestation
qui n'était pas due ou qui a été versée au mauvais destinataire. Il faut
identifier le paiement, l'absence de dette ou l'erreur et le bénéficiaire.
L'enrichissement injustifié est subsidiaire : il suppose un enrichissement,
un appauvrissement corrélatif et l'absence de justification juridique.

13. Paiement et extinction

Le paiement est l'exécution de la prestation due. Il faut vérifier le payeur,
le destinataire, la date, le montant, l'imputation et la preuve. L'obligation
peut aussi s'éteindre par compensation, remise de dette, novation, confusion,
prescription, transaction ou impossibilité définitive selon le droit
applicable.

Lorsqu'il existe plusieurs débiteurs ou créanciers, il faut distinguer la
division des parts, la solidarité et la garantie. La solidarité permet au
créancier de demander le tout à l'un des débiteurs lorsqu'elle résulte de la
loi ou du contrat. Le débiteur qui paie au-delà de sa part dispose d'un recours
selon les règles applicables.

PARTIE VI — CONTRATS SPÉCIAUX

14. Vente et échange

La vente organise le transfert d'un bien ou d'un droit contre un prix. Elle
doit identifier la chose, le prix, le transfert, la délivrance, les risques,
les garanties et les modalités de paiement. La conformité, les vices, la
réserve de propriété et les conditions de retour doivent être traités selon le
droit applicable. L'échange suit une logique voisine, chaque partie fournissant
un bien ou un droit en contrepartie d'un autre.

15. Bail à usage d'habitation ou professionnel

Le bail confère une jouissance temporaire contre un loyer. Il précise la
désignation des lieux, la durée, le loyer, les charges, l'état des lieux, les
réparations, l'assurance, la sous-location, la cession et la fin du contrat.
Le bailleur délivre un bien conforme et assure la jouissance paisible. Le
locataire paie, use raisonnablement des lieux, respecte leur destination et
restitue le bien. Les régimes d'habitation et professionnel doivent être
distingués.

16. Prestation, entreprise et mandat

Une prestation doit décrire le livrable, les critères d'acceptation, les
délais, les dépendances, la propriété des résultats, la confidentialité, la
maintenance et la responsabilité. Le mandat confie un pouvoir d'agir pour le
compte d'une personne. Le mandataire respecte les instructions, rend compte et
évite les conflits d'intérêts; le mandant fournit les moyens et rembourse les
frais justifiés.

17. Prêt, dépôt, partenariat et transaction

Le prêt précise la remise, la durée, la restitution, la rémunération et les
garanties. Le dépôt organise la garde et la restitution d'un bien. Le
partenariat précise les apports, les rôles, la propriété des résultats, les
revenus, les pertes, la sortie et le règlement des différends. La transaction
décrit le litige, les concessions réciproques, les obligations, les délais et
les conséquences d'un manquement.

PARTIE VII — TECHNIQUE CONTRACTUELLE ET MÉTHODE

18. Rédiger un contrat professionnel

Une rédaction sûre suit cette séquence : vérifier les parties et leurs
pouvoirs; définir les termes; décrire l'objet et les livrables; fixer les
délais; déterminer le prix; répartir les risques; régler la preuve, l'audit,
la confidentialité, les données et la propriété intellectuelle; prévoir la
sous-traitance, la force majeure, la sortie et les différends.

Chaque clause répond à quatre questions : qui agit, que doit-il faire, quand
et comment prouver l'exécution ? Une clause de prix indique la devise, les
taxes, la facturation et l'exigibilité. Une clause de délai précise le point
de départ, les événements suspensifs et la notification. Une clause de sortie
organise la liquidation des prestations en cours et la restitution des données.

19. Cas pratique et consultation

La méthode JurisIA comporte cinq étapes : établir la chronologie; qualifier la
relation; formuler la question de droit; exposer la règle et ses conditions;
appliquer chaque condition aux faits et conclure par une action concrète. Il
faut distinguer les faits certains, les faits à prouver et les hypothèses.

Les pièces utiles sont le contrat, les annexes, les factures, les preuves de
livraison, les mises en demeure, les échanges, les constats, les rapports et
les justificatifs du préjudice. Une consultation doit aussi indiquer les
délais, les risques et les solutions de négociation ou de procédure.

FICHES OPÉRATIONNELLES

Avant signature : identité et pouvoirs vérifiés; objet déterminé; prix et
taxes lisibles; durée et renouvellement précisés; délais mesurables; garanties
et responsabilité équilibrées; confidentialité, données et propriété des
livrables réglées; résiliation et différends prévus; annexes datées et signées.

En cas d'inexécution : conserver les preuves; qualifier le manquement; vérifier
la clause; mettre en demeure; mesurer le dommage; limiter son aggravation;
choisir un remède proportionné; vérifier la prescription; négocier sans
renoncer implicitement à ses droits.

CONCLUSION

Le droit des obligations devient maîtrisable lorsque l'on relie qualification,
preuve, exécution et remède. Un contrat efficace rend l'exécution observable,
répartit les risques et prévoit une réponse au désaccord. La responsabilité et
les quasi-contrats complètent cette logique en traitant les situations nées en
dehors d'un accord.

